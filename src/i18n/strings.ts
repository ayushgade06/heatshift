export const STRINGS: Record<Lang, Record<StringKey, string>> = { en, hi, mr, es };

export function t(lang: Lang, key: StringKey, vars: Record<string, string | number> = {}): string {
  return STRINGS[lang][key].replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}

/** "5 h 50 m" in the given language. */
export function fmtDuration(lang: Lang, minutes: number): string {
  const m = Math.round(minutes);
  const h = Math.floor(m / 60);
  const r = m % 60;
  const H = t(lang, 'hoursShort');
  const M = t(lang, 'minutesShort');
  if (h === 0) return `${r} ${M}`;
  return r === 0 ? `${h} ${H}` : `${h} ${H} ${r} ${M}`;
}
